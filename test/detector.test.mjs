// Run: node --test
import { test } from 'node:test';
import assert from 'node:assert/strict';
import '../src/settings.js';
import '../src/detector.js';
import '../src/sites.js';

const { detect, mergeSettings, siteForHost, DEFAULTS } = globalThis.BAS;
const ALL = { emDash: true, phrases: true };

test('flags any em dash', () => {
  assert.equal(detect('Great video\u2014really insightful.', ALL).rule, 'emDash');
  assert.equal(detect('This is huge \u2014 and nobody is talking about it', ALL).rule, 'emDash');
  assert.equal(detect('\u2014', ALL).rule, 'emDash');
});

test('does not flag hyphens, en dashes or double hyphens', () => {
  assert.equal(detect('well-made video - loved it', ALL), null);
  assert.equal(detect('pages 10\u201312 were great', ALL), null);
  assert.equal(detect('wait -- what?', ALL), null);
  assert.equal(detect('', ALL), null);
  assert.equal(detect(null, ALL), null);
});

test('flags high-precision AI phrases', () => {
  const slop = [
    'As an AI language model, I cannot have opinions.',
    'Certainly! Here\u2019s a summary of the video.',
    "It's not just a song, it's a journey.",
    "In today's fast-paced world, we all need this.",
    'Navigating the complexities of modern life is hard.',
    'What a rich tapestry of emotions.',
    'Let us delve into the nuances of this topic.',
    'As of my knowledge cutoff, that is correct.',
    'Sure! Here\u2019s what I think'
  ];
  for (const text of slop) assert.equal(detect(text, ALL)?.rule, 'phrases', text);
});

test('leaves ordinary human comments alone', () => {
  const human = [
    'lol this is the best thing I have seen all week',
    'first',
    'Not just me then? It is so good.',
    'I hope this helps someone who had the same problem',
    'Great question, I was wondering the same',
    'the drop at 2:31 is insane!!!',
    'Can someone explain what happened at the end?',
    'this thumbnail was generated by AI lol',
    'we retrained on my training data last week'
  ];
  for (const text of human) assert.equal(detect(text, ALL), null, text);
});

test('rules can be switched off independently', () => {
  assert.equal(detect('nice\u2014', { emDash: false, phrases: true }), null);
  assert.equal(detect('As an AI language model', { emDash: true, phrases: false }), null);
  assert.equal(detect('As an AI language model\u2014', { emDash: false, phrases: true }).rule, 'phrases');
});

test('mergeSettings tolerates junk and keeps defaults', () => {
  assert.deepEqual(mergeSettings(undefined), JSON.parse(JSON.stringify(DEFAULTS)));
  const merged = mergeSettings({ enabled: 'yes', mode: 'nuke', rules: { emDash: false, extra: true }, sites: null });
  assert.equal(merged.enabled, true);
  assert.equal(merged.mode, 'replace');
  assert.equal(merged.rules.emDash, false);
  assert.equal(merged.rules.phrases, true);
  assert.equal('extra' in merged.rules, false);
  assert.equal(merged.sites.youtube, true);
  assert.equal(mergeSettings({ mode: 'hide' }).mode, 'hide');
});

test('siteForHost matches supported hosts and subdomains only', () => {
  assert.equal(siteForHost('www.youtube.com').id, 'youtube');
  assert.equal(siteForHost('x.com').id, 'x');
  assert.equal(siteForHost('twitter.com').id, 'x');
  assert.equal(siteForHost('web.facebook.com').id, 'facebook');
  assert.equal(siteForHost('www.instagram.com').id, 'instagram');
  assert.equal(siteForHost('www.linkedin.com').id, 'linkedin');
  assert.equal(siteForHost('notyoutube.com'), null);
  assert.equal(siteForHost('example.com'), null);
});
